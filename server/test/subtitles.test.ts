import { describe, expect, it } from 'vitest';
import { buildApp } from '../src/app.js';
import { rightsOf } from '../src/rights.js';
import { downloadUrl, internetArchive, toItem } from '../src/sources/internetArchive.js';
import { describeSubtitleFile, isArchiveDownloadUrl, languageCode, pickSubtitles, toVtt } from '../src/subtitles.js';
import { createHttp } from '../src/http.js';
import { fakeHttp } from './helpers.js';

const url = (name: string) => `https://archive.org/download/x/${name}`;

describe('describeSubtitleFile', () => {
  it('reconnaît les sous-titres automatiques d’Internet Archive', () => {
    expect(describeSubtitleFile('Doctorin1946.asr.srt')).toMatchObject({ auto: true });
    expect(describeSubtitleFile('1944_Eve_of_Battle_512kb.autogenerated.vtt')).toMatchObject({ auto: true });
  });
  it('lit le code de langue d’un fichier déposé à la main', () => {
    expect(describeSubtitleFile('film.fr.srt')).toMatchObject({ lang: 'fr', auto: false });
    expect(describeSubtitleFile('film_en.vtt')).toMatchObject({ lang: 'en', auto: false });
  });
  it('ne prend pas la fin d’un mot pour une langue', () => {
    expect(describeSubtitleFile('movie_hd.srt')?.lang).toBeUndefined();
    expect(describeSubtitleFile('film.srt')?.lang).toBeUndefined();
  });
  it('ignore les autres fichiers', () => {
    expect(describeSubtitleFile('film.mp4')).toBeNull();
    expect(describeSubtitleFile('film.srt.txt')).toBeNull();
  });
});

describe('pickSubtitles', () => {
  it('préfère le WebVTT au SRT et ne garde qu’une piste par langue', () => {
    const t = pickSubtitles(
      [
        { name: 'a.asr.srt', size: 9000 },
        { name: 'a.asr.vtt', size: 9100 },
        { name: 'a.mp4', size: 99999 },
      ],
      url,
      'en',
    );
    expect(t).toEqual([{ url: url('a.asr.vtt'), lang: 'en', auto: true }]);
  });
  it('met les sous-titres humains avant les automatiques et ignore les fichiers vides', () => {
    const t = pickSubtitles(
      [
        { name: 'a.asr.vtt', size: 5000 },
        { name: 'a.fr.srt', size: 4000 },
        { name: 'vide.asr.srt', size: 0 },
        { name: 'prive.fr.srt', size: 4000, private: 'true' },
      ],
      url,
    );
    expect(t.map((x) => [x.lang, x.auto])).toEqual([
      ['fr', false],
      [undefined, true],
    ]);
  });
  it('rend une liste vide sans sous-titres', () => {
    expect(pickSubtitles([{ name: 'a.mp4' }], url)).toEqual([]);
  });
});

describe('toVtt', () => {
  it('convertit un SRT en WebVTT', () => {
    const srt = '﻿1\r\n00:00:01,500 --> 00:00:03,000\r\nBonjour\r\n\r\n2\r\n00:00:04,000 --> 00:00:05,250\r\nSalut\r\n';
    const vtt = toVtt(srt);
    expect(vtt.startsWith('WEBVTT\n\n')).toBe(true);
    expect(vtt).toContain('00:00:01.500 --> 00:00:03.000');
    expect(vtt).toContain('Bonjour');
    expect(vtt).not.toContain(',500');
  });
  it('laisse un WebVTT intact', () => {
    const v = 'WEBVTT\n\n00:00:01.000 --> 00:00:02.000\nOk\n';
    expect(toVtt(v)).toBe(v);
  });
  it('ne touche pas aux virgules du texte', () => {
    expect(toVtt('1\n00:00:01,000 --> 00:00:02,000\nUn, deux, 00:00:09,123\n')).toContain('Un, deux, 00:00:09,123');
  });
});

describe('isArchiveDownloadUrl', () => {
  it('accepte uniquement les sous-titres d’archive.org', () => {
    expect(isArchiveDownloadUrl('https://archive.org/download/x/a.asr.vtt')).toBe(true);
    expect(isArchiveDownloadUrl('https://ia800000.us.archive.org/5/items/x/a.srt')).toBe(true);
  });
  it('refuse le reste (autres hôtes, protocoles, ports, fichiers)', () => {
    for (const bad of [
      'https://evil.test/download/x/a.vtt',
      'https://archive.org.evil.test/download/x/a.vtt',
      'http://archive.org/download/x/a.vtt',
      'https://archive.org:8443/download/x/a.vtt',
      'https://user:pw@archive.org/download/x/a.vtt',
      'https://archive.org/download/x/a.mp4',
      'https://archive.org/metadata/x.vtt',
      'file:///etc/passwd',
      'pas une url',
    ]) {
      expect(isArchiveDownloadUrl(bad), bad).toBe(false);
    }
  });
});

describe('languageCode', () => {
  it('normalise les libellés d’Internet Archive', () => {
    expect(languageCode('English')).toBe('en');
    expect(languageCode(['fre', 'eng'])).toBe('fr');
    expect(languageCode('Français')).toBe('fr');
    expect(languageCode('Klingon')).toBeUndefined();
    expect(languageCode(undefined)).toBeUndefined();
  });
});

describe('Internet Archive : langue, documentaires sensibles, sous-titres', () => {
  it('renseigne la langue et marque les documentaires de guerre comme sensibles', () => {
    const item = toItem({ identifier: 'a', title: 'Eve of Battle', mediatype: 'movies', language: 'eng', collection: ['wwIIarchive', 'movies'] });
    expect(item).toMatchObject({ language: 'en', sensitive: true });
    expect(toItem({ identifier: 'b', title: 'Un film', mediatype: 'movies', collection: ['feature_films'] })?.sensitive).toBeUndefined();
  });

  it('resolve() renvoie les sous-titres trouvés', async () => {
    const meta = {
      metadata: { mediatype: 'movies', language: 'eng' },
      files: [
        { name: 'film.mp4', format: 'h.264', size: '5000000', source: 'derivative' },
        { name: 'film.asr.srt', format: 'SubRip', size: '9000', source: 'original' },
        { name: 'film.asr.vtt', format: 'Web Video Text Tracks', size: '9100', source: 'derivative' },
      ],
    };
    const r = await internetArchive.resolve('film', 'video', fakeHttp({ '/metadata/film': meta }));
    expect(r.subtitles).toEqual([{ url: downloadUrl('film', 'film.asr.vtt'), lang: 'en', auto: true }]);
  });
});

describe('droits : œuvres du gouvernement américain', () => {
  it('signale « doute », jamais « libre », avec l’explication correspondante', () => {
    expect(rightsOf({ sourceId: 'z', title: 'Battle of Midway', year: 1942, creator: 'United States. Navy' })).toEqual({ fr: 'unclear', basis: 'government', uncertain: true });
  });
  it('un créateur protégé l’emporte sur l’origine gouvernementale', () => {
    expect(rightsOf({ sourceId: 'z', title: 'Donald Duck in Nutzi Land', year: 1942, creator: 'Walt Disney Studios' })?.fr).toBe('protected');
  });
});

describe('GET /api/subtitle', () => {
  const srt = '1\n00:00:01,000 --> 00:00:02,000\nHello\n';
  const app = () => buildApp({ http: fakeHttp({ '/download/x/a.asr.srt': srt }), sources: [], staticDir: null });

  it('relaie un sous-titre en WebVTT, depuis notre propre origine', async () => {
    const res = await app().inject({ url: `/api/subtitle?url=${encodeURIComponent('https://archive.org/download/x/a.asr.srt')}` });
    expect(res.statusCode).toBe(200);
    expect(res.headers['content-type']).toContain('text/vtt');
    expect(res.body.startsWith('WEBVTT')).toBe(true);
    expect(res.body).toContain('00:00:01.000 --> 00:00:02.000');
  });

  it('refuse toute adresse qui n’est pas un sous-titre d’archive.org', async () => {
    for (const bad of ['https://evil.test/download/x/a.vtt', 'http://169.254.169.254/latest/meta-data/', '']) {
      const res = await app().inject({ url: `/api/subtitle?url=${encodeURIComponent(bad)}` });
      expect(res.statusCode, bad).toBe(400);
    }
    expect((await app().inject({ url: '/api/subtitle' })).statusCode).toBe(400);
  });
});

describe('http.text', () => {
  const build = (fetchImpl: typeof fetch) =>
    createHttp({ fetchImpl, lookupImpl: async () => [{ address: '93.184.216.34' }], proxied: false, retries: 0 });

  it('télécharge un petit fichier texte', async () => {
    const http = build(async () => new Response('WEBVTT\n\nok', { status: 200 }));
    expect(await http.text('https://archive.org/download/x/a.vtt')).toBe('WEBVTT\n\nok');
  });

  it('refuse un fichier trop gros, déclaré ou non', async () => {
    const declared = build(async () => new Response('x', { status: 200, headers: { 'content-length': '9999999' } }));
    await expect(declared.text('https://archive.org/download/x/a.vtt', { maxBytes: 1000 })).rejects.toThrow(/too large/i);
    const stream = build(async () => new Response('y'.repeat(5000), { status: 200 }));
    await expect(stream.text('https://archive.org/download/x/b.vtt', { maxBytes: 1000 })).rejects.toThrow(/too large/i);
  });

  it('refuse une adresse non publique (protection SSRF)', async () => {
    const http = build(async () => new Response('secret'));
    await expect(http.text('http://127.0.0.1/a.vtt')).rejects.toThrow();
  });
});

describe('langue par défaut des actualités Universal', () => {
  it('est l’anglais, pour la fiche comme pour les sous-titres', async () => {
    expect(toItem({ identifier: 'n', title: 'Eve of Battle', mediatype: 'movies', collection: ['universal_newsreels'] })?.language).toBe('en');
    const meta = {
      metadata: { mediatype: 'movies', collection: ['universal_newsreels'] },
      files: [{ name: 'n.mp4', format: 'h.264', size: '1000000' }, { name: 'n_512kb.autogenerated.vtt', size: '3000' }],
    };
    const r = await internetArchive.resolve('n', 'video', fakeHttp({ '/metadata/n': meta }));
    expect(r.subtitles?.[0]).toMatchObject({ lang: 'en', auto: true });
  });
});

describe('Internet Archive : épisode précis dans un document', () => {
  it('resolve(…, fichier) ne garde que ce fichier, même au-delà des 8 premiers liens', async () => {
    const files = Array.from({ length: 12 }, (_, i) => ({ name: `Ep ${i + 1}.mp4`, format: 'h.264', size: '1000000', source: 'derivative' }));
    const r = await internetArchive.resolve('serie', 'video', fakeHttp({ '/metadata/serie': { metadata: { mediatype: 'movies' }, files } }), 'Ep 11.mp4');
    expect(r.links.filter((l) => l.type === 'stream').map((l) => l.url)).toEqual([downloadUrl('serie', 'Ep 11.mp4')]);
  });
});
